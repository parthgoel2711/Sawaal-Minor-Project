import { formatCell } from "./format";
import type { Turn } from "../types";

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const MAX_ROWS = 25;

/** A self-contained HTML report of a conversation: questions, answers, SQL and the first rows of each result. */
export function buildReport(turns: Turn[], databaseName: string): string {
  const done = turns.filter((t) => t.status === "done" && (t.sql || t.summary));
  const when = new Date().toLocaleString();
  const sections = done
    .map((t, i) => {
      const r = t.result;
      const table = r
        ? `<table><thead><tr>${r.columns.map((c, ci) => `<th class="${r.column_types[ci] === "number" ? "num" : ""}">${esc(c)}</th>`).join("")}</tr></thead><tbody>${r.rows
            .slice(0, MAX_ROWS)
            .map(
              (row) =>
                `<tr>${row.map((v, ci) => `<td class="${typeof v === "number" ? "num" : ""}">${esc(formatCell(v, r.columns[ci]))}</td>`).join("")}</tr>`,
            )
            .join("")}</tbody></table>${r.row_count > MAX_ROWS ? `<p class="note">Showing the first ${MAX_ROWS} of ${r.row_count} rows.</p>` : ""}`
        : "";
      return `<section>
  <h2>${i + 1}. ${esc(t.question ?? "Query written by hand")}</h2>
  ${t.summary ? `<p class="answer">${esc(t.summary)}</p>` : ""}
  ${t.explanation ? `<p class="expl">${esc(t.explanation)}</p>` : ""}
  ${t.sql ? `<pre>${esc(t.sql)}</pre>` : ""}
  ${t.error ? `<p class="err">${esc(t.error)}</p>` : table}
</section>`;
    })
    .join("\n");

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Sawaal report: ${esc(databaseName)}</title>
<style>
  body{font:15px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif;color:#1d1e22;max-width:860px;margin:40px auto;padding:0 20px}
  header{border-bottom:3px solid #1d1e22;padding-bottom:12px;margin-bottom:28px}
  h1{margin:0;font-size:28px} header p{margin:4px 0 0;color:#667085}
  section{margin-bottom:34px;break-inside:avoid} h2{font-size:19px;margin:0 0 10px}
  .answer{background:#f6f6f4;border-left:4px solid #c0392b;padding:10px 14px;font-size:17px;margin:0 0 10px}
  .expl,.note{color:#667085;margin:0 0 10px} .err{color:#b8372e}
  pre{background:#f6f6f4;border:1px solid #dfe3ea;border-radius:8px;padding:10px 12px;white-space:pre-wrap;font:12.5px/1.5 ui-monospace,Menlo,monospace}
  table{border-collapse:collapse;width:100%;font-size:13.5px} th,td{border-bottom:1px solid #e4e7ec;padding:6px 10px;text-align:left}
  th{background:#f0f0ed} .num{text-align:right;font-variant-numeric:tabular-nums}
  footer{color:#667085;font-size:12.5px;border-top:1px solid #e4e7ec;padding-top:10px}
</style></head><body>
<header><h1>Sawaal report</h1><p>${esc(databaseName)} · ${esc(when)} · ${done.length} question${done.length === 1 ? "" : "s"}</p></header>
${sections || "<p>Nothing to report yet.</p>"}
<footer>Generated by Sawaal. Every query ran read-only.</footer>
</body></html>`;
}
